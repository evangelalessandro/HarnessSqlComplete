       CONCAT(N'Cella dimostrativa ', n),
       CASE WHEN n % 5 = 0 THEN N'HOLD' ELSE N'STD' END
FROM (SELECT ROW_NUMBER() OVER (ORDER BY (SELECT NULL)) AS n FROM sys.all_objects) AS x;
